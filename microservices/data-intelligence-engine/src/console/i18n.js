let LANG = localStorage.getItem("die.lang") || ((navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en");

function t(key, vars) {
  let s = (LANG === "zh" && I18N_ZH[key]) || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}
function setLang(lang) { LANG = lang; localStorage.setItem("die.lang", lang); }
function applyI18n(root = document) {
  document.documentElement.lang = LANG === "zh" ? "zh-CN" : "en";
  root.querySelectorAll("[data-i18n]").forEach(el => {
    if (!el.dataset.i18n) el.dataset.i18n = el.textContent.trim();
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => (el.placeholder = t(el.dataset.i18nPh)));
  root.querySelectorAll("[data-i18n-title]").forEach(el => (el.title = t(el.dataset.i18nTitle)));
}
